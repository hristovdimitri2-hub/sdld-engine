"""program.md — „програмата на екипа“ по модела на karpathy/autoresearch.

Там: human edits program.md, agent edits train.py. Тук: човекът редактира
program.md в папката на проекта; агентите го ЧЕТЕТ във всяко извикване и
не могат да го пренапишат (loop.PROTECTED_FILES).

Файлът се създава веднъж от шаблона при първи старт и НИКОГА не се
презаписва — редакциите на човека оцеляват при следващо пускане.
"""
from __future__ import annotations

import os
from pathlib import Path

PROGRAM_MD = """# програма — как работи този екип

Този файл го редактира ЧОВЕКЪТ. Агентите го четат при всяко извикване и
не го променят. Това е „кодът“ на организацията (по модела на
karpathy/autoresearch): пипай тук, за да промениш поведението на екипа,
а не в кода на двигателя.

## Цел
Един договор → план → изпълнение → ГЕЙТ (реални тестове) → одит.
Не се твърди „готово“, докато гейтът и одитът не минат.

## Какво пипа инженерът
- ПИПА: кода на проекта (src/ и т.н.).
- НЕ ПИПА: tests/, .ai-brain/, config/, conftest.py, pytest.ini,
  program.md — тестовете и досието дава човек/планът, програмата — човекът.

## ГЕЙТ
Реални тестове, винаги (и в dry режим): {python} -m unittest discover -s tests.
Таймаут на опит: gate.timeout_s в config/policy.json — прекалено бавният
опит се убива и се брои за провал (kill-rule, по модела на autoresearch:
5 мин фиксиран budget, 10 мин = убий и отхвърли).

## БЮДЖЕТ
Бюджетът спира ПРЕДИ плащане: precheck преди всеки опит. Лимитите са в
config/policy.json. Живият режим тръгва само с изрично „давай“ от човека.

## ЖУРНАЛ (.ai-brain/journal.tsv)
Всеки опит = един ред: keep | discard | crash.
- keep — гейтът минa → запазваме промяната;
- discard — гейтът провали (или таймаут) → връщаме я;
- crash — инструментът/извикването гръмна → поправяме или ескалираме.
Историята се чете от Journal.last_loc() — не се помни в главата.

## Критерий за простота
По-добро с по-малко редове = вземи (simplification win).
Минат гейт с много нов код = огледай дали може по-кратко.
Кодът расте, а гейтът не минава = търси по-просто, не повече код.
0.001 подобрение с 20 реда грозен код не си струва; равно подобрение с
изтрит код — струва.

## Автономност
След старта екипът не спира да пита „продължавам ли?“ — докато бюджетът
стига и state е active, цикълът продължава. Спира се само: по бюджет
(pause), по блокиращ провал (ескалация) или с човешка намеса.
"""


def ensure_program(project: Path) -> Path:
    """Създаща program.md от шаблона АКО липсва; никога не презаписва."""
    p = Path(project) / "program.md"
    if p.exists():
        return p
    tmp = p.with_name("program.md.tmp")
    tmp.write_text(PROGRAM_MD, encoding="utf-8")
    os.replace(tmp, p)  # атомарно: прекъсване ≠ половин шаблон
    return p


def load_program(project: Path) -> str:
    """Текстът на програмата; '' ако човекът я е изтрил (всичко е Allowed)."""
    p = Path(project) / "program.md"
    if not p.exists():
        return ""
    return p.read_text(encoding="utf-8")
